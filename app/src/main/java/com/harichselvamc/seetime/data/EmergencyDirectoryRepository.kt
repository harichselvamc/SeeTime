        /**
         * Detects the best matching country from a timezone ID string.
         */
        fun findCountryForTimezone(zoneIdStr: String): EmergencyContactInfo? {
            // First priority: direct match inside timezoneHints
            val exactHint = COUNTRIES_DATABASE.find { country ->
                country.timezoneHints.any { hint ->
                    zoneIdStr.equals(hint, ignoreCase = true) ||
                        zoneIdStr.contains(hint, ignoreCase = true) ||
                        hint.contains(zoneIdStr, ignoreCase = true)
                }
            }
            if (exactHint != null) return exactHint

            // Second priority: match city name in timezone path
            val cityPart = zoneIdStr.substringAfterLast('/').replace('_', ' ')
            return COUNTRIES_DATABASE.find { country ->
                country.countryName.contains(cityPart, ignoreCase = true) ||
                    country.timezoneHints.any { it.contains(cityPart, ignoreCase = true) }
            } ?: COUNTRIES_DATABASE.find { country ->
                val regionPart = zoneIdStr.substringBefore('/')
                country.region.equals(regionPart, ignoreCase = true)
            }
        }

        /**
         * Finds a country by its ISO 3166-1 alpha-2 code.
         */
        fun findCountryByIso(isoCode: String): EmergencyContactInfo? {
            return COUNTRIES_DATABASE.find { it.countryIsoCode.equals(isoCode.trim(), ignoreCase = true) }
        }

        /**
         * Finds a country by international calling prefix.
         */
        fun findCountryByCallingCode(callingCode: String): EmergencyContactInfo? {
            val clean = if (callingCode.startsWith("+")) callingCode else "+$callingCode"
            return COUNTRIES_DATABASE.find { it.callingCode.equals(clean.trim(), ignoreCase = true) }
        }

        /**
         * Formats a local number into E.164 international standard format.
         */
        fun formatInternationalNumber(callingCode: String, localNumber: String): String {
            val cleanLocal = localNumber.replace(Regex("[^0-9]"), "").trimStart('0')
            val prefix = if (callingCode.startsWith("+")) callingCode else "+$callingCode"
            return "$prefix $cleanLocal"
        }

        /**
         * Generates an emergency SOS SMS beacon text with timezone & local dispatch information.
         */
        fun composeEmergencySmsBeacon(
            country: EmergencyContactInfo,
            timezoneId: String,
            customNote: String? = null
        ): String {
            val timestamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"))
            return buildString {
                append("🚨 EMERGENCY SOS BEACON 🚨\n")
                append("I require immediate emergency assistance.\n\n")
                append("📍 Location / Timezone: $timezoneId (${country.countryName} ${country.flagEmoji})\n")
                append("📞 Local Dispatch Numbers: Police ${country.police}, Ambulance ${country.ambulance}, Fire ${country.fire}\n")
                append("🌐 Country Dialing Code: ${country.callingCode}\n")
                append("⏱ Timestamp: $timestamp\n")
                if (!customNote.isNullOrBlank()) {
                    append("ℹ️ Details: $customNote\n")
                }
                append("Sent via SeeTime Global Emergency HUD.")
            }
        }
    }

    /**
     * Total number of sovereign countries in the offline emergency database.
     */
    fun getCountryCount(): Int = COUNTRIES_DATABASE.size

    /**
     * Search and filter countries by query string and region.
     */
    fun searchCountries(query: String, regionFilter: String? = null): List<EmergencyContactInfo> {
        val q = query.trim().lowercase()
        return _countries.value.filter { c ->
            val matchRegion = regionFilter == null || regionFilter.equals("All", ignoreCase = true) || c.region.equals(regionFilter, ignoreCase = true)
            val matchQuery = q.isEmpty() ||
                c.countryName.lowercase().contains(q) ||
                c.countryIsoCode.lowercase().contains(q) ||
                c.callingCode.contains(q) ||
                c.universalEmergency.contains(q) ||
                c.police.contains(q) ||
                c.ambulance.contains(q) ||
                c.fire.contains(q) ||
                (c.touristPolice != null && c.touristPolice.lowercase().contains(q)) ||
                c.timezoneHints.any { it.lowercase().contains(q) }
            matchRegion && matchQuery
        }
    }

    /**
     * Launches a dialer intent for the given emergency telephone number.
     */
    fun launchDialer(context: Context, number: String) {
        val cleanNumber = number.substringBefore('(').substringBefore('/').replace(Regex("[^0-9+]"), "").trim()
        val intent = Intent(Intent.ACTION_DIAL, Uri.parse("tel:$cleanNumber")).apply {
            flags = Intent.FLAG_ACTIVITY_NEW_TASK
        }
        try {
            context.startActivity(intent)
        } catch (_: Exception) {
            // Dialer unavailable on emulator/device
        }
    }

    /**
     * Launches SMS composer for the emergency beacon.
     */
    fun launchSmsBeacon(context: Context, smsBody: String) {
        val intent = Intent(Intent.ACTION_SENDTO, Uri.parse("smsto:")).apply {
            putExtra("sms_body", smsBody)
            flags = Intent.FLAG_ACTIVITY_NEW_TASK
        }
        try {
            context.startActivity(intent)
        } catch (_: Exception) {
            // SMS app unavailable
        }
    }
